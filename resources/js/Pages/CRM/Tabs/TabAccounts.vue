<script setup>
import { computed } from 'vue';

const props = defineProps({
    accounts: {
        type: Array,
        default: () => []
    }
});

const withContactsCount = computed(() => {
    return props.accounts.filter(a => (a.contacts_count || 0) > 0).length;
});

const withDealsCount = computed(() => {
    return props.accounts.filter(a => (a.deals_count || 0) > 0).length;
});

const totalRevenue = computed(() => {
    const total = props.accounts.reduce((sum, a) => sum + parseFloat(a.annual_revenue || 0), 0);
    return formatCurrency(total);
});

function getInitials(name) {
    const words = name?.split(' ') || [];
    return words.slice(0, 2).map(w => w.charAt(0)).join('').toUpperCase();
}

function formatCurrency(amount) {
    if (!amount || amount === 0) return '$0';
    return new Intl.NumberFormat('en-US', {
        style: 'currency',
        currency: 'USD',
        minimumFractionDigits: 0,
        maximumFractionDigits: 0
    }).format(amount);
}

function truncate(str, length) {
    if (!str) return '';
    return str.length > length ? str.substring(0, length) + '...' : str;
}
</script>
